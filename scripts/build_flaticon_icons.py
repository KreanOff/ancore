"""Build the local UIcons SVG subset from the official, pinned npm archive.

Build-only dependency: fonttools. Usage: python scripts/build_flaticon_icons.py ARCHIVE
The application itself needs neither Python font tools nor a web font at runtime.
"""

import hashlib
import io
import json
from pathlib import Path
import re
import sys
import tarfile

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont


ROOT = Path(__file__).resolve().parent.parent
VERSION = '3.3.1'
ARCHIVE_SHA256 = '2c7b6e3725241d3f00ad6345e6eed66b5b3625ff201fbb5bd14acbc057acc05f'


def build(archive):
    digest = hashlib.sha256(Path(archive).read_bytes()).hexdigest()
    if digest != ARCHIVE_SHA256:
        raise ValueError('The archive does not match the pinned Flaticon release.')
    aliases = json.loads((ROOT / 'scripts/flaticon-icon-map.json').read_text())
    with tarfile.open(archive) as package:
        metadata = json.load(package.extractfile('package/package.json'))
        if metadata['name'] != '@flaticon/flaticon-uicons' or metadata['version'] != VERSION:
            raise ValueError(f'Expected @flaticon/flaticon-uicons {VERSION}')
        css = package.extractfile('package/css/regular/rounded.css').read().decode()
        codepoints = dict(re.findall(r'\.fi-rr-([a-z0-9-]+):before\{content:"\\([a-f0-9]+)"\}', css))
        font = TTFont(io.BytesIO(package.extractfile('package/css/uicons-regular-rounded-KDJ23353.woff').read()))
        license_text = package.extractfile('package/LICENSE').read()
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    scale = 24 / font['head'].unitsPerEm
    icons = {}
    for name in sorted(set(aliases.values())):
        pen = SVGPathPen(glyphs, ntos=lambda value: format(round(value, 3), 'g'))
        transformed = TransformPen(pen, (scale, 0, 0, -scale, 0, font['hhea'].ascent * scale))
        glyphs[cmap[int(codepoints[name], 16)]].draw(transformed)
        icons[name] = pen.getCommands()
    output = ROOT / 'static/vendor/flaticon'
    output.mkdir(parents=True, exist_ok=True)
    data = {'aliases': aliases, 'icons': icons}
    (output / 'uicons.js').write_text(
        f'// Flaticon UIcons Regular Rounded {VERSION}. See LICENSE and README.md.\n'
        '// Generated by scripts/build_flaticon_icons.py; do not edit by hand.\n'
        'window.AncoreFlaticon = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
    )
    (output / 'LICENSE').write_bytes(license_text)
    css_icons = {
        'check-white': ('check', 'white'),
        'minus-white': ('minus', 'white'),
        'chevron-down-gray': ('angle-small-down', '#64748b'),
        'circle-dashed-mask': ('circle-dashed', 'black'),
        'clock-mask': ('clock', 'black'),
        'circle-check-mask': ('check-circle', 'black'),
        'circle-x-mask': ('circle-x', 'black'),
        'circle-minus-mask': ('minus-circle', 'black'),
        'x-mask': ('x', 'black'),
    }
    for filename, (name, color) in css_icons.items():
        (output / f'{filename}.svg').write_text(
            f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="{color}">'
            f'<path d="{icons[name]}"/></svg>\n'
        )
    print(f'Built {len(icons)} Flaticon icons for {len(aliases)} application names.')
    print('Source SHA256:', digest)


if __name__ == '__main__':
    build(sys.argv[1])
